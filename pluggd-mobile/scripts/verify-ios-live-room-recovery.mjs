import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
import { QueryClient } from '@tanstack/react-query';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const module = { exports: {} };
const source = readFileSync(new URL('../src/features/live/liveRoomLoading.ts', import.meta.url), 'utf8');
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module, exports: module.exports, Error });
const { requireLiveRooms } = module.exports;
const client = new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: Infinity } } });
const queryKey = ['native-live-rooms-recovery'];
let response = { data: null, error: { message: 'Private provider detail' } };
const query = () => client.fetchQuery({ queryKey, queryFn: () => requireLiveRooms(Promise.resolve(response)) });
await assert.rejects(query, /Live rooms could not be loaded/);
assert.equal(client.getQueryData(queryKey), undefined);
response = { data: [{ id: 'real-room', status: 'live' }], error: null };
await query();
response = { data: null, error: { message: 'Network unavailable' } };
await assert.rejects(query, /Please try again/);
assert.equal(client.getQueryData(queryKey)[0].id, 'real-room');
response = { data: [], error: null };
assert.deepEqual(await query(), []);
client.clear();
console.log('PASS: cold failure remains an error, cached rooms survive failed refresh, retry recovers a genuine empty result; provider details stay out of copy.');
