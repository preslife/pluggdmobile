import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const source = readFileSync(new URL('../src/features/listeningRoom/roomViewState.ts',import.meta.url),'utf8');
const module = {exports:{}};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module,exports:module.exports,Date,Map,Number,Promise});
const {RoomViewCache,createRoomSeekQueue,roomTimestamp} = module.exports;
assert.equal(roomTimestamp(0),'0:00');assert.equal(roomTimestamp(65.9),'1:05');assert.equal(roomTimestamp(null),'--:--');assert.equal(roomTimestamp(NaN),'--:--');
let now=0; const cache=new RoomViewCache(()=>now);
cache.write('a','mix',{tab:'room',draft:'a private draft',position:120,angle:50,placed:true});
assert.equal(cache.read('a','mix').position,120); assert.equal(cache.read('a','mix').draft,'a private draft');
assert.equal(cache.read('b','mix').draft,''); assert.equal(cache.read('a','mix').position,0,'old actor cannot restore after account switch');
cache.write('a','mix',{angle:100,position:-1,draft:'x'.repeat(700)});
assert.equal(cache.read('a','mix').angle,65);assert.equal(cache.read('a','mix').position,0);assert.equal(cache.read('a','mix').draft.length,500);
now+=30*60000+1;assert.equal(cache.read('a','mix').draft,'','draft expires');
for(let i=0;i<10;i++)cache.write('a',String(i),{position:i+1});assert.equal(cache.read('a','0').position,0,'cache bounded');
cache.clear();assert.equal(cache.read('a','9').position,0);
const tick=()=>new Promise(resolve=>setTimeout(resolve,0));
let current=true,complete;const positions=[];let failed=0;
const queue=createRoomSeekQueue({current:()=>current,seek:async n=>{positions.push(n);await new Promise(resolve=>{complete=resolve;});},failed:()=>failed++});
queue.request(10);queue.request(20);queue.request(30);assert.deepEqual(positions,[10]);assert.equal(queue.busy,true);
complete();await tick();assert.deepEqual(positions,[10,30],'latest queued seek wins');
queue.request(40);current=false;complete();await tick();assert.deepEqual(positions,[10,30],'source/account change cancels queued seek');
current=true;queue.request(50);queue.dispose();complete();await tick();queue.request(60);assert.deepEqual(positions,[10,30,50]);
const errors=createRoomSeekQueue({current:()=>true,seek:async()=>{throw Error('offline');},failed:()=>failed++});
errors.request(NaN);errors.request(-2);await tick();assert.equal(failed,0);
errors.request(5);await tick();assert.equal(failed,1);assert.equal(errors.busy,false);
console.log('Listening-room state: account/expiry/bounds/restore, latest-only seek, source cancellation, dispose and error recovery passed.');
