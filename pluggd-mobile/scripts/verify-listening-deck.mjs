const manifest = JSON.parse(await readFile(join(root, 'assets/listening-room/bundle-manifest.json'), 'utf8'));
assert.equal(createHash('sha256').update(html).digest('hex'), manifest.html.sha256);
assert.equal(manifest.model.triangles, 738094);
assert(!/<(?:audio|video|iframe)\b|<script[^>]+src=/i.test(html), 'bundle contains no second player or executable network load');
assert(html.includes("connect-src blob:")); assert(html.includes("media-src 'none'"));
