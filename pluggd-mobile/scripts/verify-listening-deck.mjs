import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(process.env.PLUGGD_DECK_TOOLCHAIN_ROOT ?? root, 'package.json'));
const { build } = require('esbuild');
async function moduleFrom(path) {
  const result = await build({ entryPoints: [join(root, path)], bundle: true, write: false, platform: 'node', format: 'esm' });
  return import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
}
const { createCueGate, parseDeckEvent, isDeckSnapshot, coverImageUrl } = await moduleFrom('src/features/listeningRoom/deckBridge.ts');
const cue = createCueGate();
cue.sync('alice:mix-a', 1, true);
assert.equal(cue.touchdown(true, 'lowering'), null, 'music waits for the actual contact pose');
assert.equal(cue.touchdown(true, 'tracking'), 1);
assert.equal(cue.touchdown(true, 'tracking'), null, 'one callback per cue');
cue.sync('alice:mix-a', 2, true); cue.sync('alice:mix-a', 2, false); cue.sync('alice:mix-a', 2, true);
assert.equal(cue.touchdown(true, 'tracking'), null, 'backgrounded cue stays cancelled on return');
cue.sync('alice:mix-a', 3, true); cue.sync('alice:mix-a', 4, true);
assert.equal(cue.touchdown(true, 'tracking'), 4, 'replacement cue supersedes prior pending work');
cue.sync('bob:mix-b', 1, true); assert.equal(cue.touchdown(true, 'tracking'), 1, 'new source has its own cue history');
const state = { kind: 'state', version: 1, session: 'a', mixId: 'mix-a', sequence: 1, duration: 100, position: 3,
  playing: false, engaged: true, visible: true, reducedMotion: false, cueRequestId: null, parkRequestId: null, coverUrl: null, viewAngle: 35.5, chapters: [0, 30] };
assert(isDeckSnapshot(state));
for (const patch of [{ position: NaN }, { duration: Infinity }, { position: 101 }, { cueRequestId: -1 }, { parkRequestId: -1 }, { viewAngle: 66 },
  { coverUrl: 'javascript:alert(1)' }, { chapters: [101] }, { sequence: 0.5 }, { visible: 1 }]) assert(!isDeckSnapshot({ ...state, ...patch }));
assert.equal(coverImageUrl('https://user:password@example.com/a.png'), null);
assert.equal(coverImageUrl('file:///private/secret.png'), null);
assert.equal(parseDeckEvent('{'), null);
assert.equal(parseDeckEvent(JSON.stringify({ version: 1, session: 'a', mixId: 'a', sequence: 1, kind: 'seek', seconds: -5 })), null);
assert.equal(parseDeckEvent(JSON.stringify({ version: 1, session: 'a', mixId: 'a', sequence: 1, kind: 'eval', code: 'bad' })), null);
const { createArmMotion, progressToYaw, yawToProgress } = await moduleFrom('src/features/listeningRoom/renderer/deckMotion.renderer.ts');
const rig = JSON.parse(await readFile(join(root, 'assets/listening-room/rig-config.json'), 'utf8'));
for (const ratio of [0, 0.5, 1]) assert(Math.abs(yawToProgress(progressToYaw(ratio, rig), rig) - ratio) < 1e-9);
const arm = createArmMotion(rig);
assert.equal(arm.update({ now: 0, source: 'a' }).phase, 'parked');
assert.equal(arm.update({ now: 1, source: 'a', playing: true, progress: 0.5 }).phase, 'lifting');
assert.equal(arm.update({ now: 1.4, source: 'a', playing: true, progress: 0.5 }).phase, 'travelling');
assert.equal(arm.update({ now: 2.1, source: 'a', playing: true, progress: 0.5 }).phase, 'lowering');
const contact = arm.update({ now: 2.6, source: 'a', playing: true, progress: 0.5 });
assert.equal(contact.phase, 'tracking'); assert.equal(contact.lift, rig.tonearm.loweredLift);
const paused = arm.update({ now: 3, source: 'a', playing: false, progress: 0.5, holdAtTime: true });
assert.equal(paused.phase, 'paused'); assert.equal(paused.yaw, contact.yaw); assert.equal(paused.lift, contact.lift);
arm.update({ now: 4, source: 'a', playing: false, progress: 0, forcePark: true });
const stopped = arm.update({ now: 6, source: 'a', playing: true, progress: 0.5, forcePark: true });
assert.equal(stopped.phase, 'parked'); assert.equal(stopped.placed, false);
assert.equal(stopped.yaw, rig.tonearm.restAngle); assert.equal(stopped.lift, rig.tonearm.restLift);
const outerPaused = arm.update({ now: 7, source: 'a', playing: false, progress: 0, holdAtTime: true, reducedMotion: true });
assert.equal(outerPaused.phase, 'paused'); assert.equal(outerPaused.placed, true);
assert.equal(outerPaused.yaw, rig.tonearm.outerAngle);
